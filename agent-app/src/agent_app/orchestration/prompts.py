"""编排器的提示词。

单独成文件有两个理由：

* 它和 ``state.py`` 的 ``RoutingDecision`` 是一体的——提示词里少写一个字段，
  节点就会拿到默认值，而且**不会报错**。改 schema 时回来核对这里；
* 它是这套编排里唯一「决定谁干活」的地方，改动的影响面比任何节点都大，
  要能单独 diff、单独评审。

本模块的提示词常量都用 ``str.format`` 填占位符（``ORCHESTRATOR_PROMPT`` 填四个，\
``RETRY_CONTEXT`` / ``GAP_CONTEXT`` 各填两个，``DS_PROMPT`` 填四个，``HC_PROMPT``\
填六个，``COACH_CHECK_PROMPT`` 填三个，``COACH_REVISE_PROMPT`` 填两个），所以正文里
不能再出现别的花括号——要写 JSON 示例得先转义成 ``{{``。

``DS_PROMPT`` 与 ``HC_PROMPT`` 这两份是**子 Agent 的模板**：主 / 支持两种身份靠
``{role_hint}`` 区分，同一条提示词就能两头用。加 de 时照这个形状写，不要为每个
Agent 再抄一份骨架。

``HC_PROMPT`` 的收尾是 ``{revise_note}``：首轮为空串，重写那轮才塞进审核意见——
所以它自己带它的标题，不要在这一行上面再写注解（否则首轮会多出一段空标题）。
"""

